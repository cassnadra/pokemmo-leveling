# Builds data.js: every Pokemon you can order, its exp group and its level-up moves - from PokeMMO's own data.
#   level-up moves: the game's data/data.pak (tools/pak_learnsets.py -> src/pak_learnsets.json)
#   exp groups:     the Pokemon Black ROM PokeMMO runs on (tools/rom_growth.py -> src/rom_growth.json)
#   exp per level:  PokeAPI's experience.csv (the six groups' standard tables)
#   names:          species from MMO Showdown's PokeMMO dex (mmoshowdown.cc/pokemmo-data/pokedex.js), moves by
#                   number from Showdown's move list (mmoshowdown.cc/data/moves.js)
# Run: python -I tools/make_data.py src raw_csv data.js
import csv, json, os, re, sys

src, pokeapi, out = sys.argv[1:4]
def js(name):
    s = open(os.path.join(src, name + '.js'), encoding='utf-8').read()
    return json.loads(s[s.index('{'):s.rstrip().rstrip(';').rindex('}') + 1])

GROUP = {'slow': 'Slow', 'medium': 'Medium Fast', 'fast': 'Fast', 'medium-slow': 'Medium Slow',
         'slow-then-very-fast': 'Erratic', 'fast-then-very-slow': 'Fluctuating'}
with open(os.path.join(pokeapi, 'growth_rates.csv'), encoding='utf-8') as f: growth = {r['id']: r['identifier'] for r in csv.DictReader(f)}
exp = {}
with open(os.path.join(pokeapi, 'experience.csv'), encoding='utf-8') as f:
    for r in csv.DictReader(f): exp.setdefault(GROUP[growth[r['growth_rate_id']]], [0] * 101)[int(r['level'])] = int(r['experience'])

group = {int(k): v for k, v in json.load(open(os.path.join(src, 'rom_growth.json'))).items()}
pak = {int(k): v for k, v in json.load(open(os.path.join(src, 'pak_learnsets.json'))).items()}
dex = js('pokedex')
names = {v['num']: v['name'] for v in dex.values() if 1 <= v.get('num', 0) <= 649 and not v.get('forme')}
names.update({29: 'Nidoran♀', 32: 'Nidoran♂'})
# move numbers -> names: Showdown's own list first (PokeMMO's renames 237 Hidden Power -> "Hidden Power Water", 258 Hail -> Snowscape)
move_name = {}
for n, name in re.findall(r'[{,][a-z0-9]+:\{num:(-?\d+),.*?,name:"([^"]+)"', open(os.path.join(src, 'moves_base.js'), encoding='utf-8').read()):
    move_name.setdefault(int(n), name)   # (the first: Hidden Power before its typed copies, which share 237)
for v in js('moves').values(): move_name.setdefault(v.get('num', 0), v['name'])

# the game's ids above 649 that you can own with moves of their own (matched to forms by their moves: tools/compare_pak.py).
# Left out: 656 Cherrim Sunshine, 662-664 Castform, 666 Darmanitan Zen, 667 Meloetta Pirouette (battle only),
# 665 Basculin Blue-Striped (the same moves as #550), 1000 (not a Pokemon).
FORMS = {650: (386, 'Deoxys (Attack)', 10001), 651: (386, 'Deoxys (Defense)', 10002), 652: (386, 'Deoxys (Speed)', 10003),
         653: (413, 'Wormadam (Sandy)', 10004), 654: (413, 'Wormadam (Trash)', 10005), 655: (492, 'Shaymin (Sky)', 10006),
         657: (479, 'Rotom (Heat)', 10008), 658: (479, 'Rotom (Wash)', 10009), 659: (479, 'Rotom (Frost)', 10010),
         660: (479, 'Rotom (Fan)', 10011), 661: (479, 'Rotom (Mow)', 10012)}

def moves(gid):   # [[levels], name]: Lv 1 first, then by level
    out = {}
    for m, lv in pak[gid]:
        out.setdefault(move_name[m], []).append(lv)
    return sorted(([sorted(set(l)), n] for n, l in out.items()), key=lambda e: e[0][0])

species = [{'uid': n, 'id': n, 'img': n, 'name': names[n], 'group': group[n], 'moves': moves(n)} for n in range(1, 650)]
for gid, (n, name, img) in FORMS.items():
    species.append({'uid': gid, 'id': n, 'img': img, 'name': name, 'group': group[n], 'moves': moves(gid)})
species.sort(key=lambda s: (s['id'], s['uid']))

with open(out, 'w', encoding='utf-8') as f:
    f.write('// generated by tools/make_data.py from PokeMMO\'s own data (data.pak level-up moves, the Black ROM\'s exp groups)\n')
    f.write('const EXP = ' + json.dumps(exp, separators=(',', ':')) + ';\n')
    f.write('const SPECIES = ' + json.dumps(species, separators=(',', ':'), ensure_ascii=False) + ';\n')
print(len(species), 'entries')
